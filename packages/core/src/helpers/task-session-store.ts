import { randomBytes } from 'node:crypto'
import { existsSync } from 'node:fs'
import { mkdir, readFile, rename, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { type TaskSession, TaskSessionSchema } from '../schema/prepare-task.js'

function sessionsDir(projectRoot: string): string {
  return join(projectRoot, '.vibegraph', 'cache', 'sessions')
}

function sessionPath(projectRoot: string, taskId: string): string {
  if (!isSafeTaskId(taskId)) {
    throw new Error(`Invalid taskId: ${taskId}`)
  }
  return join(sessionsDir(projectRoot), `${taskId}.json`)
}

/**
 * Whitelist guard against path-traversal via user-provided taskId (the MCP
 * client controls this value). Allows the alphabet generated by
 * `generateTaskId` (alphanumeric + `.` `_` `:` `-`); forbids `/` `\` and
 * therefore any directory escape.
 *
 * Callers (`loadTaskSession` / `writeTaskSession`) treat a failure here as
 * "session not found" rather than escalating, by design — surfacing the
 * specific "you tried path traversal" reason would leak implementation
 * details to a potential attacker without giving the legitimate caller
 * any actionable information they don't already have from the
 * `TASK_SESSION_NOT_FOUND` error code returned by `validate_diff`.
 *
 * If a future audit surface is desired, an `onInvalidTaskId` callback hook
 * is the smallest viable extension — keep the silent-failure as the default
 * to preserve the current "never throws on read" contract.
 */
function isSafeTaskId(taskId: string): boolean {
  return /^task_[A-Za-z0-9._:-]+$/.test(taskId)
}

/**
 * Generate a deterministic-shape task id: `task_<YYYY-MM-DD>_<8-char-hex>`.
 * Pass a custom Date for reproducibility in tests; otherwise uses now.
 */
export function generateTaskId(now: Date = new Date()): string {
  const date = now.toISOString().slice(0, 10)
  const rand = randomBytes(4).toString('hex')
  return `task_${date}_${rand}`
}

/**
 * Read a task session by id. Returns null if file absent or malformed.
 */
export async function loadTaskSession(
  projectRoot: string,
  taskId: string,
): Promise<TaskSession | null> {
  let filePath: string
  try {
    filePath = sessionPath(projectRoot, taskId)
  } catch {
    return null
  }
  if (!existsSync(filePath)) return null
  try {
    const raw = await readFile(filePath, 'utf-8')
    return TaskSessionSchema.parse(JSON.parse(raw))
  } catch {
    return null
  }
}

/**
 * Atomically write a task session. Validates via Zod before writing.
 */
export async function writeTaskSession(projectRoot: string, session: TaskSession): Promise<void> {
  const validated = TaskSessionSchema.parse(session)
  const finalPath = sessionPath(projectRoot, session.taskId)
  const tmpPath = `${finalPath}.tmp`
  await mkdir(dirname(finalPath), { recursive: true })
  await writeFile(tmpPath, `${JSON.stringify(validated, null, 2)}\n`, 'utf-8')
  await rename(tmpPath, finalPath)
}
