import { existsSync } from 'node:fs'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { DEFAULT_IGNORE_PATTERNS } from '@codearch/core'

// ─── Config YAML ──────────────────────────────────────────────────────────────

export interface GenerateConfigYmlOptions {
  projectRoot: string
  /** Project name (used as project.name in config). */
  projectName: string
  /** Skip if .vibegraph/config.yml exists. Set true to overwrite. */
  overwrite?: boolean
}

export interface GenerateConfigYmlResult {
  path: string
  written: boolean
  /** Reason for not writing (when written: false). */
  skipped?: 'exists'
}

const CONFIG_YML_TEMPLATE = (name: string): string =>
  `# Vibe Graph configuration — see https://github.com/vibegraph/vibe-graph for the schema.
project:
  name: ${name}

subsystemDetection:
  # 'auto' detects from monorepo packages or src/<dir> heuristics.
  # 'manual' uses only the subsystems list below.
  # 'hybrid' uses manual entries with auto fallback for unmatched files.
  mode: auto

# Add explicit subsystem definitions if 'auto' detection isn't sufficient.
# subsystems:
#   - id: auth
#     title: Authentication
#     layer: domain  # 'domain' | 'horizontal' | 'infra' | 'external' | 'unknown'
#     match:
#       - src/auth/**

# Override detector thresholds (defaults: fan-out=6, fan-in=8).
# detectors:
#   core/fan-out:
#     threshold: 10
`

export async function generateConfigYml(
  opts: GenerateConfigYmlOptions,
): Promise<GenerateConfigYmlResult> {
  const path = join(opts.projectRoot, '.vibegraph', 'config.yml')
  if (existsSync(path) && opts.overwrite !== true) {
    return { path, written: false, skipped: 'exists' }
  }
  await mkdir(dirname(path), { recursive: true })
  await writeFile(path, CONFIG_YML_TEMPLATE(opts.projectName), 'utf-8')
  return { path, written: true }
}

// ─── .vibegraphignore ─────────────────────────────────────────────────────────

export interface GenerateIgnoreFileOptions {
  projectRoot: string
  /** Skip if .vibegraphignore exists. Set true to overwrite. */
  overwrite?: boolean
}

export interface GenerateIgnoreFileResult {
  path: string
  written: boolean
  skipped?: 'exists'
}

const IGNORE_HEADER = `# Vibe Graph ignore file — gitignore syntax, including negations (!important.ts).
# Generated by \`vibe-graph init\`. Edit freely; .env entries are recommended for safety.

`

export async function generateIgnoreFile(
  opts: GenerateIgnoreFileOptions,
): Promise<GenerateIgnoreFileResult> {
  const path = join(opts.projectRoot, '.vibegraphignore')
  if (existsSync(path) && opts.overwrite !== true) {
    return { path, written: false, skipped: 'exists' }
  }
  const body = `${IGNORE_HEADER}${DEFAULT_IGNORE_PATTERNS.join('\n')}\n`
  await writeFile(path, body, 'utf-8')
  return { path, written: true }
}

// ─── .gitignore append (idempotent) ───────────────────────────────────────────

export interface AppendGitignoreOptions {
  projectRoot: string
}

export interface AppendGitignoreResult {
  path: string
  /** Lines that were appended (empty array if file already contained them all). */
  appended: string[]
  /** True if the file was newly created (had to write the header section). */
  created: boolean
}

/** Lines Vibe Graph manages in the project's .gitignore. */
export const MANAGED_GITIGNORE_LINES: readonly string[] = [
  '.vibegraph/cache/',
  '.vibegraph/logs/',
  '.superpowers/',
]

const MARKER_BEGIN = '# >>> vibe-graph >>>'
const MARKER_END = '# <<< vibe-graph <<<'

export async function appendGitignore(
  opts: AppendGitignoreOptions,
): Promise<AppendGitignoreResult> {
  const path = join(opts.projectRoot, '.gitignore')
  let current = ''
  let created = false
  if (existsSync(path)) {
    current = await readFile(path, 'utf-8')
  } else {
    created = true
  }

  // Determine which managed lines are missing
  const currentLines = new Set(
    current
      .split('\n')
      .map((l) => l.trim())
      .filter((l) => l.length > 0),
  )

  const missing: string[] = []
  for (const line of MANAGED_GITIGNORE_LINES) {
    if (!currentLines.has(line)) missing.push(line)
  }

  if (missing.length === 0) {
    return { path, appended: [], created: false }
  }

  // Append a marked block at the end. If the file already has our markers,
  // replace the block. Otherwise append a fresh one.
  let next: string
  const markerRegex = new RegExp(
    `${escapeRegex(MARKER_BEGIN)}[\\s\\S]*?${escapeRegex(MARKER_END)}\\n?`,
    'g',
  )
  if (markerRegex.test(current)) {
    next = current.replace(markerRegex, buildManagedBlock(MANAGED_GITIGNORE_LINES))
  } else {
    const trimmed = current.replace(/\n+$/, '')
    next =
      trimmed.length > 0
        ? `${trimmed}\n\n${buildManagedBlock(MANAGED_GITIGNORE_LINES)}`
        : buildManagedBlock(MANAGED_GITIGNORE_LINES)
  }

  await writeFile(path, next, 'utf-8')
  return { path, appended: missing, created }
}

function buildManagedBlock(lines: readonly string[]): string {
  return `${MARKER_BEGIN}\n${lines.join('\n')}\n${MARKER_END}\n`
}

function escapeRegex(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}

// ─── MCP config (Claude Code / Cursor) ────────────────────────────────────────

export type McpTarget = 'claude-code' | 'cursor'

export interface GenerateMcpConfigOptions {
  projectRoot: string
  /** Which IDE's MCP config to write. */
  target: McpTarget
  /** Skip if the target file exists. Set true to overwrite. */
  overwrite?: boolean
  /** Optional override of the vibegraph server entry (advanced; defaults are correct for v0). */
  serverEntry?: {
    command: string
    args: string[]
  }
}

export interface GenerateMcpConfigResult {
  path: string
  written: boolean
  /** When written: false, why we skipped. */
  skipped?: 'exists' | 'already-configured'
  /** True if we merged the vibegraph entry into an existing user file. */
  merged: boolean
}

/**
 * Default vibegraph entry. Uses npx so the user doesn't need a global install.
 * `-y` (npm 7+) auto-accepts the install prompt when vibe-graph isn't cached.
 */
const DEFAULT_VIBEGRAPH_ENTRY = {
  command: 'npx',
  args: ['-y', '@codearch/cli', 'mcp'],
}

const VIBEGRAPH_KEY = 'vibegraph'

interface McpConfigShape {
  mcpServers?: Record<string, { command?: string; args?: string[]; env?: Record<string, string> }>
  [k: string]: unknown
}

/**
 * Generate (or merge) the MCP config for a target IDE.
 *
 * - Claude Code → `<projectRoot>/.mcp.json`
 * - Cursor → `<projectRoot>/.cursor/mcp.json`
 *
 * If the file exists and HAS NO `mcpServers.vibegraph` entry, we MERGE the
 * vibegraph entry into the existing config (preserving any other servers).
 * If `mcpServers.vibegraph` already exists, we skip (status: 'already-configured')
 * unless overwrite=true.
 *
 * If the file doesn't exist, we create it with just the vibegraph entry.
 */
export async function generateMcpConfig(
  opts: GenerateMcpConfigOptions,
): Promise<GenerateMcpConfigResult> {
  const path = mcpConfigPath(opts.projectRoot, opts.target)
  const entry = opts.serverEntry ?? DEFAULT_VIBEGRAPH_ENTRY

  let current: McpConfigShape = {}
  let fileExisted = false

  if (existsSync(path)) {
    fileExisted = true
    try {
      const raw = await readFile(path, 'utf-8')
      const parsed = JSON.parse(raw) as McpConfigShape
      current = parsed
    } catch {
      // Corrupt JSON — treat as empty for merge purposes if overwrite, else skip
      if (opts.overwrite !== true) {
        return { path, written: false, skipped: 'exists', merged: false }
      }
      current = {}
    }
  }

  const mcpServers = (current.mcpServers ?? {}) as Record<
    string,
    { command?: string; args?: string[] }
  >
  const hasVibegraph = VIBEGRAPH_KEY in mcpServers

  if (hasVibegraph && opts.overwrite !== true) {
    return { path, written: false, skipped: 'already-configured', merged: false }
  }

  // Merge: preserve other servers, set/replace vibegraph
  const nextServers = {
    ...mcpServers,
    [VIBEGRAPH_KEY]: { command: entry.command, args: [...entry.args] },
  }
  const next: McpConfigShape = { ...current, mcpServers: nextServers }

  await mkdir(dirname(path), { recursive: true })
  await writeFile(path, `${JSON.stringify(next, null, 2)}\n`, 'utf-8')

  // If file existed AND we kept other servers in the config, we merged.
  const otherKeys = Object.keys(mcpServers).filter((k) => k !== VIBEGRAPH_KEY)
  const merged = fileExisted && otherKeys.length > 0

  return { path, written: true, merged }
}

function mcpConfigPath(projectRoot: string, target: McpTarget): string {
  switch (target) {
    case 'claude-code':
      return join(projectRoot, '.mcp.json')
    case 'cursor':
      return join(projectRoot, '.cursor', 'mcp.json')
  }
}
